"""Regenerate _data/publications.yml from ORCID, Crossref/DataCite and scripts/publications_curation.yml."""
import re
import urllib.parse

from common import ROOT, get_json, load_yaml, write_yaml

CURATION = ROOT / "scripts" / "publications_curation.yml"
OUTPUT = ROOT / "_data" / "publications.yml"
KINDS = {"journal-article": "journal", "proceedings-article": "conference", "posted-content": "preprint"}


def orcid_dois(orcid):
    works = get_json(f"https://pub.orcid.org/v3.0/{orcid}/works")
    for group in works["group"]:
        summary = group["work-summary"][0]
        ids = {e["external-id-type"]: e["external-id-value"] for e in (summary.get("external-ids") or {}).get("external-id", [])}
        if "doi" in ids:
            yield ids["doi"]
        else:
            print(f"warning: no DOI for '{summary['title']['title']['value']}'; add it under `extra` if wanted")


def format_author(family, given):
    initials = "".join(part[0] + "." for part in given.replace(".", " ").split())
    return f"{family}, {initials}" if initials else family


def crossref(doi):
    data = get_json(f"https://api.crossref.org/works/{urllib.parse.quote(doi)}")
    if not data:
        return None
    m = data["message"]
    venue = ", ".join(
        filter(None, [(m.get("container-title") or [""])[0],
                      m.get("volume") and f"Volume {m['volume']}",
                      m.get("article-number") or m.get("page")])
    )
    return {
        "title": re.sub(r"<[^>]+>", "", m["title"][0]),
        "authors": [format_author(a["family"], a.get("given", "")) if "family" in a else a["name"] for a in m.get("author", [])],
        "year": m["issued"]["date-parts"][0][0],
        "kind": KINDS.get(m["type"], "other"),
        "venue": venue,
    }


def datacite(doi):
    data = get_json(f"https://api.datacite.org/dois/{urllib.parse.quote(doi)}")
    if not data:
        return None
    a = data["data"]["attributes"]
    publisher = a.get("publisher")
    return {
        "title": a["titles"][0]["title"],
        "authors": [format_author(c["familyName"], c.get("givenName", "")) if c.get("familyName") else c["name"] for c in a["creators"]],
        "year": a["publicationYear"],
        "kind": "preprint",
        "venue": publisher.get("name") if isinstance(publisher, dict) else publisher,
    }


def main():
    curation = load_yaml(CURATION)
    hidden = {doi.lower() for doi in curation.get("hide") or []}
    names = curation.get("author_names") or {}
    logos = curation.get("logos") or {}
    overrides = {doi.lower(): entry for doi, entry in (curation.get("overrides") or {}).items()}

    publications = []
    for doi in orcid_dois(curation["orcid"]):
        if doi.lower() in hidden:
            continue
        pub = crossref(doi) or datacite(doi)
        if not pub:
            print(f"warning: no metadata found for {doi}; skipped")
            continue
        pub["authors"] = ", ".join(names.get(author, author) for author in pub["authors"])
        pub["doi"] = doi
        pub["logo"] = logos.get(doi.split("/")[0])
        pub.update(overrides.get(doi.lower(), {}))
        publications.append(pub)

    publications += curation.get("extra") or []
    publications.sort(key=lambda p: p["year"], reverse=True)
    publications = [{k: v for k, v in p.items() if v} for p in publications]
    write_yaml(OUTPUT, publications, "# Generated by scripts/sync_publications.py. Edit scripts/publications_curation.yml instead.\n")
    print(f"{len(publications)} publications")


if __name__ == "__main__":
    main()
