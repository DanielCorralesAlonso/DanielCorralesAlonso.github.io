"""Regenerate _data/projects.yml from GitHub repos and scripts/projects_curation.yml."""
from common import ROOT, get_json, github_headers, load_yaml, write_yaml

USER = "DanielCorralesAlonso"
TOPIC = "portfolio"
CURATION = ROOT / "scripts" / "projects_curation.yml"
OUTPUT = ROOT / "_data" / "projects.yml"
FIELDS = ["title", "description", "image", "image_bg_white", "paper", "github"]


def fetch_repos():
    repos, page = [], 1
    while True:
        batch = get_json(
            f"https://api.github.com/users/{USER}/repos?type=owner&per_page=100&page={page}",
            github_headers(),
        )
        if not batch:
            return repos
        repos.extend(batch)
        page += 1


def from_repo(repo):
    return {
        "title": repo["name"].replace("_", " ").replace("-", " "),
        "description": repo["description"],
        "image": f"https://opengraph.githubassets.com/1/{repo['full_name']}",
        "github": repo["html_url"],
    }


def main():
    curation = load_yaml(CURATION)
    repos = {repo["name"]: repo for repo in fetch_repos()}

    new = sorted(
        (r for r in repos.values() if TOPIC in r.get("topics", []) and r["name"] not in curation),
        key=lambda r: r["created_at"],
        reverse=True,
    )
    projects = [from_repo(repo) for repo in new]

    for key, entry in curation.items():
        entry = entry or {}
        if entry.get("hide"):
            continue
        if key in repos:
            entry = {**from_repo(repos[key]), **entry}
        elif not entry.get("title"):
            print(f"warning: '{key}' is not one of your public repos and has no title; skipped")
            continue
        projects.append(entry)

    projects = [{k: p[k] for k in FIELDS if p.get(k)} for p in projects]
    write_yaml(OUTPUT, projects, "# Generated by scripts/sync_projects.py. Edit scripts/projects_curation.yml instead.\n")
    print(f"{len(projects)} projects ({len(new)} from the '{TOPIC}' topic only)")


if __name__ == "__main__":
    main()
